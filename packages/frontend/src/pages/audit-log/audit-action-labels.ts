/** Every labelled action, for the action filter. */
export const AUDIT_ACTION_OPTIONS: readonly string[] = Object.keys(AUDIT_ACTION_LABELS).sort(
  (a, b) => AUDIT_ACTION_LABELS[a]!.localeCompare(AUDIT_ACTION_LABELS[b]!)
);

function humanize(value: string): string {
  const text = value.replace(/[._-]+/g, " ").trim();
  return text ? text.charAt(0).toUpperCase() + text.slice(1) : value;
}

/** The label of an action written with a variable part; null when the action is not one of those families. */
function familyLabel(action: string): string | null {
  // An AI or MCP tool call: "mcp.update_route", "ai.manage_node".
  const tool = /^(mcp|ai)\.([a-z0-9_]+)$/.exec(action);
  if (tool) return `${tool[1] === "mcp" ? "MCP" : "AI"}: ${humanize(tool[2]!)}`;
  // An account route without its own entry: "auth.passkeys_register", "auth.me_profile.update".
  const account = /^auth\.([a-z0-9_]+)(\.update|\.delete)?$/.exec(action);
  if (account) {
    const change =
      account[2] === ".delete" ? " (removed)" : account[2] === ".update" ? " (changed)" : "";
    return `Account: ${humanize(account[1]!).toLowerCase()}${change}`;
  }
  return null;
}

/** Whether an action has a label of its own (not the generic fallback). */
export function hasAuditActionLabel(action: string): boolean {
  return action in AUDIT_ACTION_LABELS || familyLabel(action) !== null;
}

/** The label of an audit action; an unknown action reads as its words. */
export function getAuditActionLabel(action: string): string {
  return AUDIT_ACTION_LABELS[action] ?? familyLabel(action) ?? formatAuditToken(action);
}
