const AUDIT_TOKEN_ACRONYMS = new Set([
  "acme",
  "ai",
  "api",
  "ca",
  "dns",
  "ip",
  "mcp",
  "oauth",
  "pki",
  "ssl",
  "tls",
]);

export function formatAuditToken(value: string): string {
  return value
    .split(/[._-]+/)
    .filter(Boolean)
    .map((word) =>
      AUDIT_TOKEN_ACRONYMS.has(word.toLowerCase())
        ? word.toUpperCase()
        : word.charAt(0).toUpperCase() + word.slice(1)
    )
    .join(" ");
}

